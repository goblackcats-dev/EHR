/* NursingSim - student page only (v30). Adds "Open Patient" (the file the instructor shares) and "My Results".
   Loaded by student.html (generated by make-student.js). Depends on app.js globals validateCaseInput, renderPatient, simulationTime, refreshSimulationView. */
(() => {
  'use strict';
  const actions = document.querySelector('.top-actions'); if (!actions) return;
  const input = document.createElement('input'); input.type = 'file'; input.accept = 'application/json,.json'; input.className = 'hidden'; input.id = 'stuFile';
  const open = document.createElement('button'); open.className = 'primary-button'; open.id = 'stuOpenBtn'; open.textContent = 'Open Patient';
  const res = document.createElement('button'); res.className = 'top-link top-button'; res.id = 'stuResultsBtn'; res.textContent = 'My Results';
  actions.appendChild(res); actions.appendChild(open); document.body.appendChild(input);
  open.addEventListener('click', () => input.click());
  res.addEventListener('click', () => NSResults.openStudentDialog());

  // The instructor's "Student View" opens this page in a new window and sends the patient here directly.
  function openCase(parsed, ask) {
    const canon = parsed && parsed.canonical ? parsed.canonical : parsed;
    if (!canon || !canon.patient) throw new Error('This file is not a NursingSim patient.');
    if (ask && typeof currentCanonicalCase !== 'undefined' && currentCanonicalCase && currentCanonicalCase.patient && !confirm('Open this patient? Your work on the patient you have open now will be replaced.')) return;
    const report = validateCaseInput(canon);
    if (report.errors > 0) throw new Error('This patient file has problems and cannot be opened. Ask your instructor for a new copy.');
    renderPatient(report.canonical);
  }
  window.addEventListener('message', e => {
    if (e.origin !== location.origin || !e.data || e.data.type !== 'nursingsim-student-case') return;
    try { openCase(e.data.file, false); } catch (err) { alert(err.message); }
  });
  if (window.opener) { try { window.opener.postMessage({ type: 'nursingsim-student-ready' }, location.origin); } catch (err) { /* opener is gone */ } }

  input.addEventListener('change', async ev => {
    const f = ev.target.files[0]; ev.target.value = ''; if (!f) return;
    try {
      openCase(JSON.parse(await f.text()), true);
    } catch (e) { alert(e.message || 'Could not open that file.'); }
  });
})();

// Secure link: https://site/?case=ID#k=KEY  -> fetch cases/ID.enc.json, unlock it with the key in the link, open the patient.
(() => {
  'use strict';
  const q = new URLSearchParams(location.search), id = q.get('case'), km = /^#k=([A-Za-z0-9_-]{20,64})$/.exec(location.hash || '');
  if (!id) return;
  const key = km && km[1];
  if (location.hash) { try { history.replaceState(null, '', location.pathname + location.search); } catch (e) { /* ignore */ } } // keep the key out of the address bar and history
  const banner = (msg) => { const d = document.createElement('div'); d.style.cssText = 'position:fixed;inset:0;background:#eef2f6;z-index:99999;display:flex;align-items:center;justify-content:center;padding:24px;text-align:center;font:18px system-ui'; d.textContent = msg; d.id = 'stuLinkMsg'; document.body.appendChild(d); return d; };
  (async () => {
    const wait = banner('Opening your patient…');
    try {
      if (!NSSecure.validId(id)) throw new Error('bad-id');
      if (!key) throw new Error('no-key');
      const res = await fetch('cases/' + encodeURIComponent(id) + '.enc.json', { cache: 'no-store', credentials: 'omit' });
      if (!res.ok) throw new Error('missing');
      const file = await NSSecure.decrypt(await res.json(), key);
      const canon = file && file.canonical ? file.canonical : file;
      const report = validateCaseInput(canon);
      if (report.errors > 0) throw new Error('invalid');
      renderPatient(report.canonical); wait.remove();
    } catch (e) {
      wait.textContent = e.message === 'missing' ? 'This patient is not available yet. Please try again in a few minutes, or ask your instructor.'
        : 'This link did not work. Open the full link from your instructor’s email again (copy the whole thing, including everything after the #).';
    }
  })();
})();
